<?php
/**
 * Уникальный блок городской страницы: условия для конкретного города + соседние города области.
 * Тексты подбираются детерминированно по slug города — страница не меняется между загрузками.
 */
defined('ABSPATH') || exit;
['key' => $key, 'd' => $d, 'city' => $city] = $args;
if (!$city) {
	return;
}
$c      = kv_city($city);
$name   = $c[0];
$in     = $c[1];
$region = KV_REGIONS[$c[2]] ?? '';
$near   = $c[2] === 'minsk'; // Минская область — можно приехать в мастерскую
$what   = mb_strtolower(mb_substr($d['short'], 0, 1)) . mb_substr($d['short'], 1); // «коврики ЭВА»

$intro = kv_pick([
	"Заказать {$what} {$in} можно не выходя из дома: оставьте заявку на сайте или напишите в Viber — мы подберём материал, цвет и рассчитаем стоимость.",
	"Жители города {$name} заказывают у нас {$what} с доставкой: изготавливаем изделие в мастерской в Минске и отправляем Европочтой.",
	"{$d['product']} {$in} — изготовление по индивидуальным размерам и доставка до ближайшего отделения Европочты.",
	"Хотите заказать {$what} {$in}? Мы работаем по всей Беларуси: принимаем заказы онлайн и доставляем готовые изделия за 1–3 дня.",
], $city . $key);

$how = empty($d['remote'])
	? kv_pick([
		'Для автомобильных ковриков достаточно назвать марку, модель и год выпуска авто — у нас собрана база более 2000 лекал, поэтому замер салона не требуется.',
		'Коврики кроятся по готовым лекалам вашей модели (в базе более 2000 автомобилей), поэтому приезжать на замер не нужно — достаточно марки, модели и года выпуска.',
		'Мы изготавливаем коврики по заводским лекалам: сообщите марку, модель и год авто, а если модели нет в базе — подскажем, как снять размеры самостоятельно.',
	], $city . 'how')
	: kv_pick([
		'Пришлите размеры или эскиз в Viber/Telegram либо через форму — изготовим изделие точно по ним.',
		'Достаточно прислать размеры и выбрать цвет — всё остальное мы сделаем сами и отправим готовый заказ.',
	], $city . 'how');

$deliv = $near
	? "Из Минской области удобно приехать к нам в мастерскую (г. Минск, ул. Тростенецкая 10): " . (empty($d['remote']) ? 'установим коврики и проверим посадку прямо при вас. ' : 'заберёте заказ сами. ') . 'Также доступна доставка Европочтой.'
	: "Отправляем заказы {$in} ({$region}) Европочтой: срок доставки 1–3 дня, оплата при получении после осмотра.";
?>
<section class="kv-sec kv-city">
	<div class="kv-wrap kv-city__grid">
		<div class="kv-content">
			<h2 class="kv-h2 kv-h2--left"><?php echo esc_html($d['short'] . ' ' . $in . ' — как заказать'); ?></h2>
			<p><?php echo esc_html($intro); ?></p>
			<p><?php echo esc_html($how); ?></p>
			<p><?php echo esc_html($deliv); ?></p>
		</div>
		<aside class="kv-city__card">
			<p class="kv-city__card-title"><?php echo kv_icon('truck'); ?>Доставка <?php echo esc_html($in); ?></p>
			<dl>
				<dt>Способ</dt><dd><?php echo $near ? 'Самовывоз / Европочта' : 'Европочта'; ?></dd>
				<dt>Срок</dt><dd>1–3 дня</dd>
				<dt>Оплата</dt><dd>При получении</dd>
				<dt>Цена изделия</dt><dd>от <?php echo (int) $d['price_from']; ?> руб.</dd>
			</dl>
			<button type="button" class="kv-btn kv-btn--block" data-modal="order" data-product="<?php echo esc_attr($d['short']); ?>">Заказать с доставкой</button>
		</aside>
	</div>
</section>
